import { build } from 'esbuild';

// Keep a directly servable bundle in the PWA, with no CDN or bare npm imports.
await build({ entryPoints: ['src/native.mjs'], outfile: 'connect.zuporta.com/assets/js/native.js',
  bundle: true, format: 'esm', platform: 'browser', target: ['ios15', 'chrome89'],
  minify: true, drop: ['console', 'debugger'], legalComments: 'inline',
  banner: { js: '// Generated by npm run build:native from src/native.mjs; do not edit directly.' } });

// A DSN is a public project destination, never a Sentry API/auth token.
const dsn = process.env.SENTRY_DSN || '';
if (dsn && !/^https:\/\/[^:@/]+@[^/]+\/\d+$/.test(dsn)) throw new Error('SENTRY_DSN must be a public HTTPS Sentry DSN.');
await build({ entryPoints: ['src/monitoring.mjs'], outfile: 'connect.zuporta.com/assets/js/monitoring.js',
  bundle: true, format: 'esm', platform: 'browser', target: ['ios15', 'chrome89'],
  minify: true, drop: ['console', 'debugger'], legalComments: 'inline',
  define: { __ZUPORTA_SENTRY_DSN__: JSON.stringify(dsn), __ZUPORTA_RELEASE__: JSON.stringify(`com.zuporta.plus@1.0.0+${process.env.GITHUB_SHA || 'local'}`) },
  banner: { js: '// Generated optional diagnostics adapter; no collection before configuration and consent.' } });
